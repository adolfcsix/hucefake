CREATE TABLE chat_conversations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users,
  role TEXT NOT NULL,
  staff_id BIGINT,
  unit_id BIGINT,
  title TEXT NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX chat_conversations_owner ON chat_conversations(user_id, updated_at DESC, id DESC);

CREATE TABLE chat_exchanges (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversation_id BIGINT NOT NULL REFERENCES chat_conversations ON DELETE CASCADE,
  question TEXT NOT NULL,
  reply JSONB NOT NULL,
  proposal_id BIGINT REFERENCES ai_proposals,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX chat_exchanges_conversation ON chat_exchanges(conversation_id,id DESC);
