-- FM05, chuyển từ Phụ lục A sang PostgreSQL.
CREATE TABLE period_definitions (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campus_id       BIGINT NOT NULL,
  period_no       SMALLINT NOT NULL,
  start_time      TIME NOT NULL,
  end_time        TIME NOT NULL,
  shift           VARCHAR(12) NOT NULL,
  effective_from  DATE NOT NULL,
  effective_to    DATE NULL,
  status          VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
  CONSTRAINT uk_pd_campus_period UNIQUE (campus_id, period_no, effective_from),
  CONSTRAINT fk_pd_campus FOREIGN KEY (campus_id) REFERENCES campuses (id),
  CONSTRAINT ck_pd_no     CHECK (period_no BETWEEN 1 AND 15),
  CONSTRAINT ck_pd_time   CHECK (start_time < end_time),
  CONSTRAINT ck_pd_shift  CHECK (shift IN ('MORNING', 'AFTERNOON', 'EVENING')),
  CONSTRAINT ck_pd_range  CHECK (effective_to IS NULL OR effective_from <= effective_to)
);
 
-- 2. Phòng dùng cho học và thi (mục 9.4 teaching_rooms)
CREATE TABLE teaching_rooms (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campus_id  BIGINT NOT NULL,
  code       VARCHAR(30) NOT NULL,
  name       VARCHAR(100) NOT NULL,
  capacity   INT NOT NULL,
  type       VARCHAR(20) NOT NULL,
  status     VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
  CONSTRAINT uk_tr_campus_code UNIQUE (campus_id, code),
  CONSTRAINT fk_tr_campus FOREIGN KEY (campus_id) REFERENCES campuses (id),
  CONSTRAINT ck_tr_capacity CHECK (capacity > 0),
  CONSTRAINT ck_tr_type     CHECK (type IN ('LECTURE', 'COMPUTER_LAB', 'LAB', 'STUDIO')),
  CONSTRAINT ck_tr_status   CHECK (status IN ('ACTIVE', 'MAINTENANCE', 'INACTIVE'))
);
 
-- 3. Ngày không tổ chức học (nghỉ lễ, thi tập trung)
CREATE TABLE non_teaching_days (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campus_id   BIGINT NULL,
  start_date  DATE NOT NULL,
  end_date    DATE NOT NULL,
  name        VARCHAR(150) NOT NULL,
  created_by  BIGINT NOT NULL,
  CONSTRAINT fk_ntd_campus FOREIGN KEY (campus_id) REFERENCES campuses (id),
  CONSTRAINT fk_ntd_created_by FOREIGN KEY (created_by) REFERENCES users (id),
  CONSTRAINT ck_ntd_dates CHECK (start_date <= end_date)
);
 
-- 4. Lớp học phần (mục 25.5 course_sections, bổ sung trường lập lịch)
CREATE TABLE course_sections (
  id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code                 VARCHAR(40) NOT NULL,
  subject_id           BIGINT NOT NULL,
  semester_id          BIGINT NOT NULL,
  capacity             INT NOT NULL,
  status               VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
  version              INT NOT NULL DEFAULT 0,
  sessions_per_week    SMALLINT NOT NULL DEFAULT 1,
  periods_per_session  SMALLINT NOT NULL DEFAULT 3,
  required_room_type   VARCHAR(20) NOT NULL DEFAULT 'LECTURE',
  start_date           DATE NOT NULL,
  end_date             DATE NOT NULL,
  created_by           BIGINT NOT NULL,
  created_at           TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at           TIMESTAMP NULL,
  CONSTRAINT uk_cs_semester_code UNIQUE (semester_id, code),
  CONSTRAINT fk_cs_subject    FOREIGN KEY (subject_id)  REFERENCES subjects (id),
  CONSTRAINT fk_cs_semester   FOREIGN KEY (semester_id) REFERENCES semesters (id),
  CONSTRAINT fk_cs_created_by FOREIGN KEY (created_by)  REFERENCES users (id),
  CONSTRAINT ck_cs_capacity   CHECK (capacity > 0),
  CONSTRAINT ck_cs_status     CHECK (status IN ('DRAFT', 'OPEN', 'CLOSED', 'CANCELLED')),
  CONSTRAINT ck_cs_sessions   CHECK (sessions_per_week BETWEEN 1 AND 6),
  CONSTRAINT ck_cs_periods    CHECK (periods_per_session BETWEEN 1 AND 6),
  CONSTRAINT ck_cs_room_type  CHECK (required_room_type IN ('LECTURE', 'COMPUTER_LAB', 'LAB', 'STUDIO')),
  CONSTRAINT ck_cs_dates      CHECK (start_date <= end_date)
);
 
-- 5. Phân công giảng viên (mục 9.4 section_assignments, tách đối tượng học ra bảng 6)
CREATE TABLE section_assignments (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  section_id       BIGINT NOT NULL,
  staff_id         BIGINT NOT NULL,
  role             VARCHAR(16) NOT NULL DEFAULT 'MAIN',
  valid_from       DATE NOT NULL,
  valid_to         DATE NULL,
  assigned_by      BIGINT NOT NULL,
  created_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  -- Mỗi lớp chỉ có một giảng viên chính đang hiệu lực
  current_main_key BIGINT GENERATED ALWAYS AS (CASE WHEN role = 'MAIN' AND valid_to IS NULL THEN section_id END) STORED,
  CONSTRAINT uk_sa_current_main UNIQUE (current_main_key),
  CONSTRAINT uk_sa_section_staff UNIQUE (section_id, staff_id, valid_from, created_at),
  CONSTRAINT fk_sa_section     FOREIGN KEY (section_id)  REFERENCES course_sections (id),
  CONSTRAINT fk_sa_staff       FOREIGN KEY (staff_id)    REFERENCES staff_profiles (id),
  CONSTRAINT fk_sa_assigned_by FOREIGN KEY (assigned_by) REFERENCES users (id),
  CONSTRAINT ck_sa_role  CHECK (role IN ('MAIN', 'ASSISTANT')),
  CONSTRAINT ck_sa_range CHECK (valid_to IS NULL OR valid_from <= valid_to)
);
 
-- 6. Lớp hành chính bắt buộc học lớp học phần
CREATE TABLE section_target_groups (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  section_id  BIGINT NOT NULL,
  group_id    BIGINT NOT NULL,
  CONSTRAINT uk_stg_section_group UNIQUE (section_id, group_id),
  CONSTRAINT fk_stg_section FOREIGN KEY (section_id) REFERENCES course_sections (id) ON DELETE CASCADE,
  CONSTRAINT fk_stg_group   FOREIGN KEY (group_id)   REFERENCES academic_groups (id)
);
 
-- 7. Thời gian bận / không muốn dạy của giảng viên
CREATE TABLE staff_availability (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  staff_id     BIGINT NOT NULL,
  semester_id  BIGINT NOT NULL,
  day_of_week  SMALLINT NOT NULL,
  period_from  SMALLINT NOT NULL,
  period_to    SMALLINT NOT NULL,
  kind         VARCHAR(8) NOT NULL,
  reason       VARCHAR(500) NULL,
  CONSTRAINT fk_av_staff    FOREIGN KEY (staff_id)    REFERENCES staff_profiles (id),
  CONSTRAINT fk_av_semester FOREIGN KEY (semester_id) REFERENCES semesters (id),
  CONSTRAINT ck_av_day   CHECK (day_of_week BETWEEN 1 AND 7),
  CONSTRAINT ck_av_range CHECK (period_from BETWEEN 1 AND 15 AND period_from <= period_to AND period_to <= 15),
  CONSTRAINT ck_av_kind  CHECK (kind IN ('BUSY', 'AVOID'))
);
 
-- 8. Lần chạy xếp lịch tự động (giải thuật di truyền)
CREATE TABLE schedule_runs (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  semester_id      BIGINT NOT NULL,
  requested_by     BIGINT NOT NULL,
  algorithm        VARCHAR(20) NOT NULL DEFAULT 'GENETIC',
  parameters       JSONB NOT NULL,
  status           VARCHAR(12) NOT NULL DEFAULT 'QUEUED',
  generations_run  INT NOT NULL DEFAULT 0,
  hard_violations  INT NULL,
  soft_penalty     DECIMAL(12,2) NULL,
  fitness          DOUBLE PRECISION NULL,
  message          VARCHAR(1000) NULL,
  created_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  started_at       TIMESTAMP NULL,
  finished_at      TIMESTAMP NULL,
  -- Mỗi học kỳ chỉ có một lần chạy đang chờ hoặc đang chạy
  active_key       BIGINT GENERATED ALWAYS AS (CASE WHEN status IN ('QUEUED', 'RUNNING') THEN semester_id END) STORED,
  CONSTRAINT uk_sr_one_active UNIQUE (active_key),
  CONSTRAINT fk_sr_semester     FOREIGN KEY (semester_id)  REFERENCES semesters (id),
  CONSTRAINT fk_sr_requested_by FOREIGN KEY (requested_by) REFERENCES users (id),
  CONSTRAINT ck_sr_status CHECK (status IN ('QUEUED', 'RUNNING', 'COMPLETED', 'FAILED', 'APPLIED', 'DISCARDED'))
);
 
-- 9. Phương án đề xuất của một lần chạy
CREATE TABLE schedule_run_items (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id          BIGINT NOT NULL,
  section_id      BIGINT NOT NULL,
  staff_id        BIGINT NOT NULL,
  room_id         BIGINT NOT NULL,
  day_of_week     SMALLINT NOT NULL,
  period_from     SMALLINT NOT NULL,
  period_count    SMALLINT NOT NULL,
  violation_note  VARCHAR(1000) NULL,
  CONSTRAINT fk_sri_run     FOREIGN KEY (run_id)     REFERENCES schedule_runs (id) ON DELETE CASCADE,
  CONSTRAINT fk_sri_section FOREIGN KEY (section_id) REFERENCES course_sections (id) ON DELETE CASCADE,
  CONSTRAINT fk_sri_staff   FOREIGN KEY (staff_id)   REFERENCES staff_profiles (id),
  CONSTRAINT fk_sri_room    FOREIGN KEY (room_id)    REFERENCES teaching_rooms (id),
  CONSTRAINT ck_sri_day     CHECK (day_of_week BETWEEN 1 AND 7),
  CONSTRAINT ck_sri_periods CHECK (period_from BETWEEN 1 AND 15 AND period_count BETWEEN 1 AND 6 AND period_from + period_count - 1 <= 15)
);
 
-- 10. Lịch định kỳ hằng tuần của lớp học phần (bản đang lập)
CREATE TABLE section_schedule_patterns (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  section_id      BIGINT NOT NULL,
  staff_id        BIGINT NOT NULL,
  room_id         BIGINT NOT NULL,
  day_of_week     SMALLINT NOT NULL,
  period_from     SMALLINT NOT NULL,
  period_count    SMALLINT NOT NULL,
  effective_from  DATE NOT NULL,
  effective_to    DATE NOT NULL,
  source          VARCHAR(10) NOT NULL DEFAULT 'MANUAL',
  run_id          BIGINT NULL,
  created_by      BIGINT NOT NULL,
  created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  version         INT NOT NULL DEFAULT 0,
  CONSTRAINT fk_ssp_section    FOREIGN KEY (section_id) REFERENCES course_sections (id) ON DELETE CASCADE,
  CONSTRAINT fk_ssp_staff      FOREIGN KEY (staff_id)   REFERENCES staff_profiles (id),
  CONSTRAINT fk_ssp_room       FOREIGN KEY (room_id)    REFERENCES teaching_rooms (id),
  CONSTRAINT fk_ssp_run        FOREIGN KEY (run_id)     REFERENCES schedule_runs (id) ON DELETE SET NULL,
  CONSTRAINT fk_ssp_created_by FOREIGN KEY (created_by) REFERENCES users (id),
  CONSTRAINT ck_ssp_day     CHECK (day_of_week BETWEEN 1 AND 7),
  CONSTRAINT ck_ssp_periods CHECK (period_from BETWEEN 1 AND 15 AND period_count BETWEEN 1 AND 6 AND period_from + period_count - 1 <= 15),
  CONSTRAINT ck_ssp_dates   CHECK (effective_from <= effective_to),
  CONSTRAINT ck_ssp_source  CHECK (source IN ('MANUAL', 'GENETIC'))
);
 
-- 11. Phiên bản thời khóa biểu theo học kỳ, liên kết hồ sơ phê duyệt dùng chung
CREATE TABLE timetable_versions (
  id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  semester_id          BIGINT NOT NULL,
  version_no           INT NOT NULL,
  status               VARCHAR(12) NOT NULL DEFAULT 'DRAFT',
  section_count        INT NOT NULL DEFAULT 0,
  approval_request_id  BIGINT NULL,
  created_by           BIGINT NOT NULL,
  created_at           TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  published_by         BIGINT NULL,
  published_at         TIMESTAMP NULL,
  -- Mỗi học kỳ có tối đa một bản đang chờ duyệt và một bản đang công bố
  submitted_key        BIGINT GENERATED ALWAYS AS (CASE WHEN status = 'SUBMITTED' THEN semester_id END) STORED,
  published_key        BIGINT GENERATED ALWAYS AS (CASE WHEN status = 'PUBLISHED' THEN semester_id END) STORED,
  CONSTRAINT uk_tv_semester_version UNIQUE (semester_id, version_no),
  CONSTRAINT uk_tv_one_submitted UNIQUE (submitted_key),
  CONSTRAINT uk_tv_one_published UNIQUE (published_key),
  CONSTRAINT uk_tv_approval UNIQUE (approval_request_id),
  CONSTRAINT fk_tv_semester     FOREIGN KEY (semester_id)         REFERENCES semesters (id),
  CONSTRAINT fk_tv_approval     FOREIGN KEY (approval_request_id) REFERENCES approval_requests (id),
  CONSTRAINT fk_tv_created_by   FOREIGN KEY (created_by)          REFERENCES users (id),
  CONSTRAINT fk_tv_published_by FOREIGN KEY (published_by)        REFERENCES users (id),
  CONSTRAINT ck_tv_status    CHECK (status IN ('DRAFT', 'SUBMITTED', 'RETURNED', 'PUBLISHED', 'SUPERSEDED')),
  CONSTRAINT ck_tv_published CHECK (status NOT IN ('PUBLISHED', 'SUPERSEDED') OR (published_by IS NOT NULL AND published_at IS NOT NULL)),
  CONSTRAINT ck_tv_submitted CHECK (status IN ('DRAFT') OR approval_request_id IS NOT NULL)
);
 
-- 12. Buổi học thực tế (mục 25.6 class_sessions)
CREATE TABLE class_sessions (
  id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  section_id            BIGINT NOT NULL,
  pattern_id            BIGINT NULL,
  timetable_version_id  BIGINT NULL,
  staff_id              BIGINT NOT NULL,
  room_id               BIGINT NULL,
  start_at              TIMESTAMP NOT NULL,
  end_at                TIMESTAMP NOT NULL,
  period_from           SMALLINT NOT NULL,
  period_count          SMALLINT NOT NULL,
  status                VARCHAR(12) NOT NULL DEFAULT 'PLANNED',
  source_session_id     BIGINT NULL,
  created_at            TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  version               INT NOT NULL DEFAULT 0,
  CONSTRAINT fk_ses_section FOREIGN KEY (section_id)           REFERENCES course_sections (id),
  CONSTRAINT fk_ses_pattern FOREIGN KEY (pattern_id)           REFERENCES section_schedule_patterns (id) ON DELETE SET NULL,
  CONSTRAINT fk_ses_version FOREIGN KEY (timetable_version_id) REFERENCES timetable_versions (id),
  CONSTRAINT fk_ses_staff   FOREIGN KEY (staff_id)             REFERENCES staff_profiles (id),
  CONSTRAINT fk_ses_room    FOREIGN KEY (room_id)              REFERENCES teaching_rooms (id),
  CONSTRAINT fk_ses_source  FOREIGN KEY (source_session_id)    REFERENCES class_sessions (id),
  CONSTRAINT ck_ses_time    CHECK (end_at > start_at),
  CONSTRAINT ck_ses_periods CHECK (period_from BETWEEN 1 AND 15 AND period_count BETWEEN 1 AND 6 AND period_from + period_count - 1 <= 15),
  CONSTRAINT ck_ses_status  CHECK (status IN ('PLANNED', 'COMPLETED', 'CANCELLED'))
);
 
-- 13. Ngoại lệ của một buổi học (mục 9.4 session_exceptions)
CREATE TABLE session_exceptions (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id       BIGINT NOT NULL,
  occurrence_date  DATE NOT NULL,
  action           VARCHAR(12) NOT NULL,
  replacement_id   BIGINT NULL,
  reason           VARCHAR(500) NOT NULL,
  created_by       BIGINT NOT NULL,
  created_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uk_se_session UNIQUE (session_id),
  CONSTRAINT uk_se_replacement UNIQUE (replacement_id),
  CONSTRAINT fk_se_session     FOREIGN KEY (session_id)     REFERENCES class_sessions (id),
  CONSTRAINT fk_se_replacement FOREIGN KEY (replacement_id) REFERENCES class_sessions (id),
  CONSTRAINT fk_se_created_by  FOREIGN KEY (created_by)     REFERENCES users (id),
  CONSTRAINT ck_se_action      CHECK (action IN ('CANCEL', 'RESCHEDULE', 'ROOM_CHANGE')),
  CONSTRAINT ck_se_replacement CHECK ((action = 'CANCEL' AND replacement_id IS NULL) OR (action <> 'CANCEL' AND replacement_id IS NOT NULL))
);

