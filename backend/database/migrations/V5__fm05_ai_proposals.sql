CREATE TABLE IF NOT EXISTS ai_proposals (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  requested_by BIGINT NOT NULL REFERENCES users,
  semester_id BIGINT NOT NULL REFERENCES semesters,
  action TEXT NOT NULL CHECK (action IN ('GENERATE','APPLY')),
  run_id BIGINT REFERENCES schedule_runs,
  parameters JSONB,
  result JSONB,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  expires_at TIMESTAMPTZ NOT NULL DEFAULT (now()+interval '15 minutes'),
  confirmed_at TIMESTAMPTZ,
  CHECK (
    (action='GENERATE' AND run_id IS NULL AND parameters IS NOT NULL)
    OR (action='APPLY' AND run_id IS NOT NULL AND parameters IS NULL)
  ),
  CHECK ((confirmed_at IS NULL) = (result IS NULL))
);
