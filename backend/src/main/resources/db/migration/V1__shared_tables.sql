-- Các bảng dùng chung tối thiểu để FM05 chạy độc lập.
CREATE TABLE roles (role_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code TEXT UNIQUE NOT NULL CHECK (code IN ('STAFF','MANAGER','LECTURER','STUDENT')), name TEXT NOT NULL);
CREATE TABLE users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, role_id BIGINT NOT NULL REFERENCES roles,
  username TEXT UNIQUE NOT NULL, email TEXT UNIQUE NOT NULL, password_hash TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'ACTIVE', version INT NOT NULL DEFAULT 0
);
CREATE TABLE organizational_units (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code TEXT UNIQUE NOT NULL, name TEXT NOT NULL);
CREATE TABLE staff_profiles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT UNIQUE NOT NULL REFERENCES users,
  code TEXT UNIQUE NOT NULL, unit_id BIGINT NOT NULL REFERENCES organizational_units,
  position TEXT, status TEXT NOT NULL DEFAULT 'ACTIVE'
);
CREATE TABLE academic_years (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code TEXT UNIQUE NOT NULL);
CREATE TABLE semesters (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, year_id BIGINT NOT NULL REFERENCES academic_years,
  code TEXT UNIQUE NOT NULL, start_date DATE NOT NULL, end_date DATE NOT NULL,
  status TEXT NOT NULL DEFAULT 'ACTIVE', CHECK (end_date >= start_date)
);
CREATE TABLE subjects (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code TEXT UNIQUE NOT NULL, name TEXT NOT NULL,
  managing_unit_id BIGINT NOT NULL REFERENCES organizational_units, credits INT NOT NULL CHECK (credits > 0),
  status TEXT NOT NULL DEFAULT 'ACTIVE'
);
CREATE TABLE curriculum_versions (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code TEXT UNIQUE NOT NULL);
CREATE TABLE academic_groups (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code TEXT UNIQUE NOT NULL,
  curriculum_id BIGINT NOT NULL REFERENCES curriculum_versions, capacity INT NOT NULL CHECK (capacity > 0)
);
CREATE TABLE campuses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code TEXT UNIQUE NOT NULL, name TEXT NOT NULL,
  address TEXT, status TEXT NOT NULL DEFAULT 'ACTIVE'
);
CREATE TABLE staff_campuses (staff_id BIGINT REFERENCES staff_profiles, campus_id BIGINT REFERENCES campuses, PRIMARY KEY(staff_id,campus_id));
CREATE TABLE work_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, kind TEXT NOT NULL,
  created_by BIGINT NOT NULL REFERENCES users, status TEXT NOT NULL DEFAULT 'PENDING',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE approval_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, work_item_id BIGINT UNIQUE NOT NULL REFERENCES work_items,
  requested_by BIGINT NOT NULL REFERENCES users, assigned_approver BIGINT REFERENCES users,
  payload JSONB NOT NULL, payload_version INT NOT NULL DEFAULT 1, policy_ref TEXT NOT NULL DEFAULT 'FM05',
  status TEXT NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','APPROVED','RETURNED','APPLIED')),
  decided_by BIGINT REFERENCES users, decided_at TIMESTAMP, decision_reason TEXT,
  CHECK (decided_by IS NULL OR decided_by <> requested_by)
);
CREATE TABLE execution_records (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, approval_request_id BIGINT UNIQUE NOT NULL REFERENCES approval_requests,
  idempotency_key TEXT UNIQUE NOT NULL, result JSONB NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE audit_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, actor_id BIGINT NOT NULL REFERENCES users,
  action TEXT NOT NULL, entity_type TEXT NOT NULL, entity_id BIGINT NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
