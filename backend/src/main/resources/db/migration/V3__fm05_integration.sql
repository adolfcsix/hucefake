CREATE TABLE section_enrollments (
  section_id BIGINT REFERENCES course_sections, student_user_id BIGINT REFERENCES users,
  status TEXT NOT NULL DEFAULT 'ENROLLED' CHECK (status IN ('ENROLLED','WITHDRAWN')),
  PRIMARY KEY(section_id,student_user_id)
);
CREATE TABLE notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users,
  message TEXT NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, read_at TIMESTAMP
);
CREATE INDEX idx_notifications_user ON notifications(user_id,id DESC);
CREATE TABLE session_change_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, session_id BIGINT REFERENCES class_sessions NOT NULL,
  staff_id BIGINT REFERENCES staff_profiles NOT NULL, action TEXT NOT NULL CHECK (action IN ('CANCEL','RESCHEDULE')),
  reason TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'PENDING' CHECK(status IN ('PENDING','APPROVED','RETURNED')),
  decision_reason TEXT, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX uk_session_pending_change ON session_change_requests(session_id) WHERE status='PENDING';
CREATE INDEX idx_enrollments_student ON section_enrollments(student_user_id);
CREATE TABLE schedule_run_progress (
  run_id BIGINT REFERENCES schedule_runs ON DELETE CASCADE, generation INT,
  hard_violations INT NOT NULL, soft_penalty NUMERIC(12,2) NOT NULL,
  PRIMARY KEY(run_id,generation)
);
